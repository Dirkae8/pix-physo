type Cat = Exclude<CategoryId, 'all'>;
type Clone = (id: number) => MaterialDef;
type MatTable = Record<string, number>;

interface P {
  rho?: number; cp?: number; k?: number; f?: number; ig?: number; bh?: number;
  ar?: number; por?: number; vis?: number; dis?: number; rep?: number;
  ts?: number; ec?: number; erh?: number;
  c?: [number, number, number]; ac?: [number, number, number];
  met?: number; rgh?: number; op?: number; em?: number;
  sty?: MaterialDef['textureStyle'];
  melt?: number; meltTo?: number;
  boil?: number; boilTo?: number;
  freeze?: number; freezeTo?: number; defT?: number;
  exp?: number; expShock?: number;
  state?: PhaseState; sel?: boolean; sol?: boolean;
  /** Полностью убрать унаследованные фазовые переходы клонируемого вещества. */
  noPhases?: boolean;
  /** Убрать унаследованную чувствительность к детонации (например у паров топлива). */
  noExplosive?: boolean;
}

interface Spec extends P {
  id: number; key: string; name: string; desc: string; cat: Cat; base: number;
}

function materialise(spec: Spec, clone: Clone): MaterialDef {
  const b = clone(spec.base);
  const d: MaterialDef = {
    ...b,
    id: spec.id,
    key: spec.key,
    name: spec.name,
    shortDesc: spec.desc,
    category: spec.cat,
    state: spec.state ?? b.state,
    selectable: spec.sel ?? true,
    density: spec.rho ?? b.density,
    specificHeat: spec.cp ?? b.specificHeat,
    thermalCond: spec.k ?? b.thermalCond,
    flammability: spec.f ?? b.flammability,
    ignitionTempC: spec.ig ?? b.ignitionTempC,
    burnHeat: spec.bh ?? b.burnHeat,
    explosivePower: spec.exp ?? b.explosivePower,
    detonationShockKPa: spec.expShock ?? b.detonationShockKPa,
    acidResistance: spec.ar ?? b.acidResistance,
    porosity: spec.por ?? b.porosity,
    waterSoluble: spec.sol ?? b.waterSoluble,
    viscosity: spec.vis ?? b.viscosity,
    dispersion: spec.dis ?? b.dispersion,
    reposeSkip: spec.rep ?? b.reposeSkip,
    tensileStrength: spec.ts ?? b.tensileStrength,
    elecCond: spec.ec ?? b.elecCond,
    elecResistanceHeat: spec.erh ?? b.elecResistanceHeat,
    defaultTempC: spec.defT ?? b.defaultTempC,
    baseColor: spec.c ?? b.baseColor,
    accentColor: spec.ac ?? b.accentColor,
    metallic: spec.met ?? b.metallic,
    roughness: spec.rgh ?? b.roughness,
    opacity: spec.op ?? b.opacity,
    emissive: spec.em ?? b.emissive,
    textureStyle: spec.sty ?? b.textureStyle,
  };
  if (spec.noPhases) {
    d.meltTempC = undefined; d.meltInto = undefined;
    d.boilTempC = undefined; d.boilInto = undefined;
    d.freezeTempC = undefined; d.freezeInto = undefined;
  }
  if (spec.noExplosive) {
    d.explosivePower = undefined;
    d.detonationShockKPa = undefined;
  }
  if (spec.meltTo !== undefined) { d.meltTempC = spec.melt; d.meltInto = spec.meltTo; }
  if (spec.boilTo !== undefined) { d.boilTempC = spec.boil; d.boilInto = spec.boilTo; }
  if (spec.freezeTo !== undefined) { d.freezeTempC = spec.freeze; d.freezeInto = spec.freezeTo; }
  return d;
}

